"""Allocate every A08 STUDY item to exactly one AUDIT part (CZ, FC, VO, RT, SC, XW). Read-only on its inputs; writes
/home/claude/a08/notes/AUDIT_ALLOCATION.md. Rule: the part that owns the mechanism counts; others cite.
- A08-AP/U/Q: the first source part ID listed in the entry's parentheses (P01->CZ, P02->FC, P03->VO, P04->RT,
  P05->SC, P06 and P07->XW).
- Inherited items, open issues, Owner-field records: the primary part in P07 section 7 (as checked).
- Notes N1 to N6: P07 section 7 (N4 none -> XW).
- Listed records of STUDY 13.6: the first P01..P06 statement cited in the row's 'Part statements' cell; none -> XW."""
import re, pathlib, collections
STUDY = pathlib.Path("/home/claude/algocore_system/doc/02_PHASE1_LEGACY_STUDY_AND_AUDIT/TOPIC_WISE_DOCUMENTATION/"
                     "A08_TECHNICAL_ANALYSIS_SR_AND_RETEST_CONTEXT/A08_STUDY_2026-11-26.md").read_text(encoding="utf-8")
P07 = pathlib.Path("/home/claude/a08/parts/A08_PRIOR_TOPIC_HANDOFFS_2026-11-26.md").read_text(encoding="utf-8")
MAP = {"P01": "CZ", "P02": "FC", "P03": "VO", "P04": "RT", "P05": "SC", "P06": "XW", "P07": "XW"}
alloc = collections.OrderedDict()

def add(key, part, basis):
    if key in alloc:
        raise SystemExit(f"DUPLICATE {key}")
    alloc[key] = (part, basis)

for kind in ("AP", "U", "Q"):
    for m in re.finditer(rf"^- \*\*(A08-{kind}-\d\d)\*\* \(([^)]*)\)", STUDY, re.M):
        src = re.search(r"P0\d", m.group(2))
        add(m.group(1), MAP[src.group(0)] if src else "XW", m.group(2)[:80])

sec7 = P07[P07.index("## 7."):P07.index("## 8.")]
for row in re.findall(r"^\| (P0[1-6]) \| ([^|]*) \| ([^|]*) \| ([^|]*) \| ([^|]*) \|", sec7, re.M):
    part = MAP[row[0]]
    for cell, label in ((row[1], "item"), (row[2], "open issue"), (row[3], "Owner-field record")):
        topic = None
        for tok in re.split(r";\s*|,\s*", cell):
            tok = tok.replace("(interface only)", "").strip()
            if not tok or tok == "none":
                continue
            mt = re.match(r"(A0\d) (.+)", tok)
            if mt:
                topic, ident = mt.group(1), mt.group(2)
            else:
                ident = tok
            key = ident if re.match(r"A0\d-\d\d", ident) else f"{topic} {ident}"
            add(key, part, f"P07 section 7, {row[0]} {label}")
    for n in re.findall(r"\bN\d\b", row[4]):
        if f"note {n}" not in alloc:
            add(f"note {n}", part, f"P07 section 7, {row[0]}")
for n in ("N1", "N2", "N3", "N4", "N5", "N6"):
    if f"note {n}" not in alloc:
        add(f"note {n}", "XW", "no primary part in P07")

s136 = STUDY[STUDY.index("### 13.6"):STUDY.index("## 14.")]
for line in s136.split("\n"):
    m = re.match(r"^\| (A0\d [A-Z]{1,3}-?\d+[a-z]?)\b", line)
    if not m:
        continue
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    src = re.search(r"P0[1-6]", cells[-1])
    key = m.group(1)
    if key in alloc:
        continue
    add(key, MAP[src.group(0)] if src else "XW", "STUDY 13.6, first part statement" if src else "STUDY 13.6, no part pointer")

out = ["# A08 AUDIT allocation (generated by A08_AUDIT_ALLOCATE.py; every item in exactly one part)", ""]
cnt = collections.Counter(p for p, _ in alloc.values())
out.append("| Part | Items |"); out.append("|---|---|")
for p in ("CZ", "FC", "VO", "RT", "SC", "XW"):
    out.append(f"| {p} | {cnt[p]} |")
out.append(f"| total | {sum(cnt.values())} |"); out.append("")
out.append("| Item | Part | Basis |"); out.append("|---|---|---|")
for k, (p, b) in alloc.items():
    out.append(f"| {k} | {p} | {b} |")
pathlib.Path("/home/claude/a08/notes/AUDIT_ALLOCATION.md").write_text("\n".join(out) + "\n", encoding="utf-8")
kinds = collections.Counter(("AP" if k.startswith("A08-AP") else "U" if k.startswith("A08-U") else "Q" if k.startswith("A08-Q")
                             else "OIR" if re.match(r"A0\d-\d\d$", k) else "note" if k.startswith("note") else "record/item") for k in alloc)
print(dict(cnt), sum(cnt.values()), dict(kinds))
